"""JW-24: requirement traceability and command schemas.

The PRD defines requirement IDs (FR-*, NFR-*) and acceptance IDs (T-*). Code and tests cite them.
`matrix()` maps each defined ID to the source and test files that cite it; `dangling()` lists IDs
cited in code that the PRD does not define, which is always a mistake. `command_schemas()` turns
the CLI's closed command contracts into JSON Schema documents.
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
ID = re.compile(r"(?<![A-Za-z0-9-])((?:N?FR)-[A-Z]{2,4}-\d{2}|T-[A-Z]{2,4}-\d{2})(?![0-9])")
DEFINED = (re.compile(r"\*\*((?:N?FR)-[A-Z]{2,4}-\d{2})\b"), re.compile(r"^\| ((?:N?FR)-[A-Z]{2,4}-\d{2}) ", re.M),
           re.compile(r"\b(T-[A-Z]{2,4}-\d{2})\b"))


def defined(prd=None):
    text = Path(prd or ROOT / "docs" / "02-prd.md").read_text(encoding="utf-8")
    return sorted({m for pattern in DEFINED for m in pattern.findall(text)})


def citations(root=None):
    root = Path(root or ROOT)
    found = {}
    for folder in ("src/jw", "tests"):
        for path in sorted((root / folder).glob("*.py")):
            for match in ID.findall(path.read_text(encoding="utf-8")):
                found.setdefault(match, set()).add(path.relative_to(root).as_posix())
    return found


def dangling(prd=None, root=None):
    known = set(defined(prd))
    return sorted(set(citations(root)) - known)


def matrix(prd=None, root=None):
    cited = citations(root)
    rows = []
    for ident in defined(prd):
        files = sorted(cited.get(ident, ()))
        rows.append({"id": ident, "src": [f for f in files if f.startswith("src/")],
                     "tests": [f for f in files if f.startswith("tests/")]})
    return rows


def render(rows):
    traced = sum(1 for r in rows if r["tests"])
    lines = ["# Requirement traceability", "",
             "Generated by `python3 scripts/check_traceability.py --write`; do not edit by hand.", "",
             f"{traced} of {len(rows)} PRD requirement and acceptance IDs are cited by at least one test. "
             "An uncited ID is not necessarily unimplemented; it has no test that names it.", "",
             "| ID | Source | Tests |", "| --- | --- | --- |"]
    for row in rows:
        lines.append(f"| {row['id']} | {', '.join(row['src']) or '-'} | {', '.join(row['tests']) or '-'} |")
    return "\n".join(lines) + "\n"


def command_schemas():
    from .cli import COMMANDS

    schemas = {}
    for name, (required, optional) in sorted(COMMANDS.items()):
        schemas[name] = {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": name,
                         "type": "object", "required": sorted(required),
                         "properties": {key: {} for key in sorted(required | optional)},
                         "additionalProperties": False}
    return schemas
